// Generates engine/firered/src/data/native-layout-variants.js from the pinned
// pret/pokefirered source. Only layouts that a native map script installs with
// `setmaplayoutindex` and that navigation cannot see in the static knowledge
// pack belong here. Usage:
//   node scripts/build-layout-variants.mjs <pokefirered-root> [output]
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {join, dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import {decodeMapGrid, decodeMetatileAttributes, parseNumericDefines} from '../engine/firered/src/extractor/primitives.js';

const root = resolve(process.argv[2] ?? '');
const output = resolve(process.argv[3] ?? join(dirname(fileURLToPath(import.meta.url)), '../engine/firered/src/data/native-layout-variants.js'));
const REVISION = 'c75f352304d529f6ba92d4f74b9cf8b5c3810788';
let revision = null;
try { revision = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], {encoding: 'utf8'}).trim(); } catch {}
if (revision !== REVISION) throw new Error(`pokefirered ${REVISION} is required (found ${revision})`);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const layouts = JSON.parse(readFileSync(join(root, 'data/layouts/layouts.json'), 'utf8')).layouts;
const metatiles = readFileSync(join(root, 'src/data/tilesets/metatiles.h'), 'utf8');
const behaviors = parseNumericDefines(readFileSync(join(root, 'include/constants/metatile_behaviors.h'), 'utf8'));
const behaviorNames = new Map(Object.entries(behaviors).filter(([n]) => n.startsWith('MB_')).map(([n, {value}]) => [value, n]));
const paths = new Map([...metatiles.matchAll(/gMetatileAttributes_(\w+)\[\]\s*=\s*INCBIN_U32\("([^"]+)"\)/g)].map(m => [`gTileset_${m[1]}`, m[2]]));
const attributes = tileset => decodeMetatileAttributes(readFileSync(join(root, paths.get(tileset))));

// Same cell decoding as src/extractor/world.js (extractWorldStructure).
function decode(id) {
  const layout = layouts.find(l => l.id === id);
  const bytes = readFileSync(join(root, layout.blockdata_filepath));
  const grid = decodeMapGrid(bytes, layout.width, layout.height);
  const primary = attributes(layout.primary_tileset), secondary = attributes(layout.secondary_tileset);
  const cells = grid.cells.map((cell, index) => {
    const isPrimary = cell.metatileId < 640;
    const a = (isPrimary ? primary : secondary)[isPrimary ? cell.metatileId : cell.metatileId - 640];
    return [cell.metatileId, cell.collision, cell.elevation, a.behavior, a.terrain, a.encounterType, a.layerType];
  });
  return {id, name: layout.name, width: layout.width, height: layout.height,
    primaryTileset: layout.primary_tileset, secondaryTileset: layout.secondary_tileset, blockDataSha256: sha256(bytes), cells};
}

const SWITCHES = [
  // data/maps/ThreeIsland_DunsparceTunnel/scripts.inc: ON_TRANSITION installs the
  // dug-out layout whenever IsNationalPokedexEnabled() (src/event_data.c).
  {map: 'MAP_THREE_ISLAND_DUNSPARCE_TUNNEL', script: 'ThreeIsland_DunsparceTunnel_OnTransition', condition: 'national-dex',
    base: 'LAYOUT_THREE_ISLAND_DUNSPARCE_TUNNEL', variant: 'LAYOUT_THREE_ISLAND_DUNSPARCE_TUNNEL_DUG_OUT'},
];
const variants = SWITCHES.map(s => {
  const base = decode(s.base), variant = decode(s.variant);
  if (base.width !== variant.width || base.height !== variant.height) throw new Error(`${s.variant} changes the map size`);
  const tilesets = new Set(variant.cells.map(([metatileId]) => metatileId < 640 ? variant.primaryTileset : variant.secondaryTileset));
  return {map: s.map, script: s.script, condition: s.condition, baseLayout: s.base, baseBlockDataSha256: base.blockDataSha256,
    layout: {id: variant.id, name: variant.name, width: variant.width, height: variant.height, blockDataSha256: variant.blockDataSha256,
      primaryTileset: variant.primaryTileset, secondaryTileset: variant.secondaryTileset,
      behaviorNames: Object.fromEntries([...new Set(variant.cells.map(c => c[3]))].sort((a, b) => a - b).map(b => [b, behaviorNames.get(b) ?? null])),
      tilesets: [...tilesets], cells: variant.cells}};
});
const text = `// Generated by scripts/build-layout-variants.mjs from pret/pokefirered ${REVISION}.
// Do not edit. Each entry is a whole layout a native map script installs with
// setmaplayoutindex; cells are [metatileId, collision, elevation, behavior,
// terrain, encounterType, layerType] in row-major order.
export const NATIVE_LAYOUT_VARIANTS = Object.freeze(${JSON.stringify({source: {repository: 'pret/pokefirered', revision: REVISION}, variants})}.variants);
`;
writeFileSync(output, text);
console.log(`wrote ${output} (${variants.length} variant)`);
