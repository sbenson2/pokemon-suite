export function expectedTrainerPayout(
  trainer,
  { moneyMultiplier = 1 } = {},
) {
  const factor = TRAINER_MONEY_FACTORS[trainer?.trainerClass];
  const party = trainer?.party;
  const lastLevel = Number(Array.isArray(party)
    ? party.at(-1)?.lvl ?? party.at(-1)?.level
    : 0);
  const multiplier = Number(moneyMultiplier);
  if (
    !Number.isFinite(factor) || factor <= 0 ||
    !Number.isSafeInteger(lastLevel) || lastLevel <= 0 ||
    !Number.isFinite(multiplier) || multiplier <= 0
  ) return null;
  const doubleBattle = trainer?.doubleBattle === true ||
    trainer?.doubleBattle === "TRUE";
  return 4 * lastLevel * multiplier * (doubleBattle ? 2 : 1) * factor;
}
